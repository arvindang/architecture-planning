#!/usr/bin/env python3
"""Render the Hydepark plats and write hydepark-site-data.js from ops/hydepark-site.json and the public-records register."""
import hashlib
import json
import subprocess
import tempfile
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'ops/hydepark-site.json'
RECORDS = ROOT / 'sources/hydepark/public-records.json'
ASSETS = ROOT / 'assets/sites/hydepark'
OUT = ROOT / 'hydepark-site-data.js'


def render(doc, tmp):
    prefix = Path(tmp) / doc['id']
    subprocess.run(['pdftoppm', '-r', str(doc['dpi']), '-png', '-singlefile', str(ROOT / doc['pdf']), str(prefix)], check=True)
    im = Image.open(f'{prefix}.png').convert('RGB')
    draw = ImageDraw.Draw(im)
    for box in doc['redact']:  # boxes in rendered pixels, before rotation
        draw.rectangle(box, fill=(200, 200, 200))
    if doc['rotate']:
        im = im.rotate(doc['rotate'], expand=True)
    path = ASSETS / f"{doc['id']}.{doc['format']}"
    if doc['format'] == 'jpg':
        im.save(path, quality=85, optimize=True)
    else:
        im.convert('L').save(path, optimize=True)
    return path, im.size


def main():
    data = json.loads(SOURCE.read_text())
    data['records'] = json.loads(RECORDS.read_text())
    ASSETS.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        for doc in data['documents']:
            path, (width, height) = render(doc, tmp)
            doc.update(file=str(path.relative_to(ROOT)), width=width, height=height,
                       sha256=hashlib.sha256(path.read_bytes()).hexdigest())
    OUT.write_text('// Generated by scripts/prepare-hydepark-site.py from ops/hydepark-site.json. Do not edit.\n'
                   f'const SITE_HYDEPARK = {json.dumps(data, ensure_ascii=False)};\n')
    print(f"Wrote {OUT.name} and {len(data['documents'])} plat images")


if __name__ == '__main__':
    main()
